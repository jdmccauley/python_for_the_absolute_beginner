#This program is an example of string manipulations in python.
print("Take note that this is the text to be worked on.")
text = "Take note that this is the text to be worked on."
print("Now I'll make that all uppercase.")
print(text.lower())
print("Now all uppercase.")
print(text.upper())
print("Now with every word capitalized with in the first letter.")
print(text.title())
print("Now finally, I'll replace the word 'text' with 'quote'")
print(text.replace("text", "quote"))
